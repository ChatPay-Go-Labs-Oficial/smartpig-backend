import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Type } from 'class-transformer';
import {
  IsDecimal,
  IsNotEmpty,
  IsOptional,
  IsString,
  IsUUID,
} from 'class-validator';

export class QuoteConversionDto {
  @ApiPropertyOptional({
    description: 'Source asset. Defaults to the funding asset (USDC).',
  })
  @IsOptional()
  @IsString()
  from?: string;

  @ApiProperty({
    description: 'Target asset symbol, e.g. EURC.',
    example: 'EURC',
  })
  @IsString()
  @IsNotEmpty()
  to: string;

  @ApiProperty({
    description: 'Amount of the source asset, in whole units.',
    example: '10.00',
  })
  @IsDecimal({ decimal_digits: '0,7' })
  amount: string;

  /** The app's api client injects this into every request. */
  @ApiPropertyOptional()
  @IsOptional()
  @IsString()
  userId?: string;
}

export class CreateConversionDto {
  @ApiProperty({ description: 'UUID v4 generated by the client.' })
  @IsUUID(4)
  idempotencyKey: string;

  @ApiProperty()
  @IsString()
  @IsNotEmpty()
  walletAccountId: string;

  @ApiProperty({ description: 'Target asset symbol.', example: 'EURC' })
  @IsString()
  @IsNotEmpty()
  to: string;

  @ApiProperty({ description: 'Amount of the funding asset, in whole units.' })
  @IsDecimal({ decimal_digits: '0,7' })
  amount: string;

  @ApiPropertyOptional({
    description:
      'The vault this conversion is funding. Recorded so a conversion that ' +
      'lands without its deposit is resumable instead of a mystery balance.',
  })
  @IsOptional()
  @IsString()
  vaultId?: string;

  @ApiPropertyOptional()
  @IsOptional()
  @IsString()
  userId?: string;
}

export class SubmitConversionDto {
  @ApiProperty({
    description: 'The conversion XDR with the user signature added.',
  })
  @IsString()
  @IsNotEmpty()
  signedXdr: string;

  @ApiPropertyOptional()
  @IsOptional()
  @IsString()
  userId?: string;
}

export class PendingConversionsQuery {
  @ApiPropertyOptional()
  @IsOptional()
  @Type(() => String)
  @IsString()
  userId?: string;
}
